// Emits typed literal checks over the shared protocol contract corpus and
// runs the pinned TypeScript compiler over them. Every check is a real
// literal taken verbatim from the corpus's raw payload text: accepts must
// typecheck, rejects must be rejected (an unused @ts-expect-error directive
// is itself a failure). The emitted project lives in a temporary directory
// outside the repository and is removed after a successful run. Run through
// `npm run typecheck:protocol`.
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptsDir = dirname(fileURLToPath(import.meta.url));
const frontendDir = dirname(scriptsDir);
const repoDir = dirname(frontendDir);
const generatedDir = join(frontendDir, 'src', 'generated', 'protocol');
const corpusPath = join(repoDir, 'protocol', 'testdata', 'protocol_contract_fixtures.json');
const tsc = join(frontendDir, 'node_modules', '.bin', 'tsc');

// The generator normalizes two component names; every other component name is
// exported unchanged.
const generatedNames = { JSONObject: 'JsonObject', ImageURLPart: 'ImageUrlPart' };
const typeName = (schema) => generatedNames[schema] ?? schema;

function main() {
  const corpus = JSON.parse(readFileSync(corpusPath, 'utf8'));
  const bySchema = new Map(corpus.components.map((entry) => [entry.schema, entry]));
  const firstAccept = (schema) => bySchema.get(schema)?.accept[0]?.json;

  const workspace = mkdtempSync(join(tmpdir(), 'lightcode-protocol-fixtures-'));
  let keep = true;
  try {
    const relativeImport = relative(workspace, generatedDir).split(sep).join('/');
    const importPath = relativeImport.startsWith('.') ? relativeImport : `./${relativeImport}`;
    const sdkFunctions = corpus.operations.map(
      (operation) => operation.operation_id.charAt(0).toLowerCase() + operation.operation_id.slice(1),
    );
    const lines = [
      '// Generated by scripts/check-protocol-fixtures.mjs; literal payloads',
      '// come verbatim from the shared contract corpus.',
      `import type * as P from '${importPath}/index';`,
      `import { ${sdkFunctions.join(', ')} } from '${importPath}';`,
      `import { createClient } from '${importPath}/client';`,
      '',
    ];
    let accepts = 0;
    let rejects = 0;
    for (const component of corpus.components) {
      component.accept.forEach((fixture, index) => {
        accepts += 1;
        lines.push(`const component_${component.schema}_accept_${index}: P.${typeName(component.schema)} = ${fixture.json};`);
      });
      component.reject.forEach((fixture, index) => {
        if (fixture.typescript === false) {
          return;
        }
        rejects += 1;
        lines.push(`// @ts-expect-error ${component.schema} rejects ${fixture.name}`);
        lines.push(`const component_${component.schema}_reject_${index}: P.${typeName(component.schema)} = ${fixture.json};`);
      });
    }
    for (const operation of corpus.operations) {
      if (operation.request === '') {
        accepts += 1;
        lines.push(`const operation_${operation.operation_id}_request: P.${operation.operation_id}Data['body'] = {};`);
      } else if (operation.request !== null) {
        const payload = firstAccept(operation.request);
        if (payload === undefined) {
          throw new Error(`operation ${operation.operation_id} names unknown request component ${operation.request}`);
        }
        accepts += 1;
        lines.push(`const operation_${operation.operation_id}_request: P.${operation.operation_id}Data['body'] = ${payload};`);
      }
      for (const [status, reference] of Object.entries(operation.responses)) {
        if (reference === null) {
          throw new Error(`operation ${operation.operation_id} response ${status} has no component reference`);
        }
        const array = reference.endsWith('[]');
        const schema = array ? reference.slice(0, -2) : reference;
        const payload = firstAccept(schema);
        if (payload === undefined) {
          throw new Error(`operation ${operation.operation_id} response ${status} names unknown component ${schema}`);
        }
        accepts += 1;
        const target = status === 'default'
          ? `P.${operation.operation_id}Errors['default']`
          : `P.${operation.operation_id}Responses['${status}']`;
        lines.push(`const operation_${operation.operation_id}_response_${status}: ${target} = ${array ? `[${payload}]` : payload};`);
      }
    }
    // The SDK operation surface and the client construction the generated
    // consumer must expose, referenced as real exported values.
    lines.push(`void [${sdkFunctions.join(', ')}];`);
    lines.push(`const client = createClient({ baseUrl: 'http://127.0.0.1:0', auth: '${'0f'.repeat(32)}' });`);
    lines.push('void client;');
    writeFileSync(join(workspace, 'checks.ts'), lines.join('\n') + '\n');
    // One tsc pass: the temporary project extends the repository's protocol
    // tsconfig (the one source of compiler settings) and includes both the
    // emitted literal checks and the full generated tree, so no second
    // project pass is needed.
    const toPosix = (target) => relative(workspace, target).split(sep).join('/');
    writeFileSync(join(workspace, 'tsconfig.json'), JSON.stringify({
      extends: toPosix(join(frontendDir, 'tsconfig.protocol.json')),
      include: ['checks.ts', `${toPosix(generatedDir)}/**/*.ts`],
    }, null, 2) + '\n');

    const result = spawnSync(tsc, ['-p', join(workspace, 'tsconfig.json')], { stdio: 'inherit' });
    if (result.error) {
      throw result.error;
    }
    if (result.status !== 0) {
      console.error(`protocol fixtures: tsc rejected the emitted literal checks (${accepts} accepts, ${rejects} expected rejections); emitted project left at ${workspace}`);
      process.exitCode = result.status ?? 1;
      return;
    }
    console.log(`protocol fixtures: ${accepts} accepted literals and ${rejects} expected rejections typechecked`);
    keep = false;
  } finally {
    if (!keep) {
      rmSync(workspace, { recursive: true, force: true });
    }
  }
}

main();
